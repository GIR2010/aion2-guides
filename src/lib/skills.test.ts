import { describe, expect, it } from 'vitest';
import { charLevelFor, levelUpCost, maxSkillLevel, totalCost } from './skills';

// Наблюдения со скриншотов окна «Умения», персонаж 22 уровня (19.10.2026).
describe('стоимость повышения навыка', () => {
  it.each([
    // [текущий уровень, стоимость, навык на скриншоте]
    [1, 1, 'Ослепляющий разрез'],
    [3, 1, 'Внезапная атака'],
    [4, 2, 'Взрыв эмблемы'],
    [5, 2, 'Удар из сумрака'],
    [6, 2, 'Рев зверя'],
    [7, 4, 'Быстрый разрез'],
    [8, 4, 'Внезапное нападение'],
  ])('ур. %i → +1 стоит %i (%s)', (from, cost) => {
    expect(levelUpCost(from)).toBe(cost);
  });

  it('с 1 до 8 уровня — 13 очков', () => {
    expect(totalCost(8)).toBe(13);
  });
});

describe('ограничение уровня навыка уровнем персонажа', () => {
  it.each([
    // [открытие навыка, следующий уровень навыка, «Можно изучить на ур. перс.», навык]
    [3, 9, 24, 'Внезапное нападение'],
    [5, 8, 23, 'Неистовый шквал'],
    [14, 5, 23, 'Взрыв эмблемы'],
    [11, 6, 23, 'Удар с тыла'],
    [13, 6, 25, 'Стойка нападения'],
    [17, 4, 23, 'Внезапная атака'],
  ])('открытие %i, ур. %i → ур. перс. %i (%s)', (unlock, skillLevel, charLevel) => {
    expect(charLevelFor(skillLevel, unlock)).toBe(charLevel);
    expect(maxSkillLevel(charLevel - 1, unlock)).toBe(skillLevel - 1);
  });

  it.each([
    // Навыки, которые на 22 уровне подняты без ограничения: [открытие, уровень навыка]
    [1, 8], // Быстрый разрез 7, следующий 8 — доступен
    [4, 7], // Пронзание сердца 6 → 7
    [7, 7], // Удар торнадо 6 → 7
    [6, 6], // Выжидание момента 5 → 6
  ])('на 22 уровне открытие %i позволяет ур. %i', (unlock, skillLevel) => {
    expect(maxSkillLevel(22, unlock)).toBeGreaterThanOrEqual(skillLevel);
  });

  it('больше 10 очками не поднять', () => {
    expect(maxSkillLevel(45, 1)).toBe(10);
  });
});
